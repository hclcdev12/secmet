//! Langue de rédaction du PDF (français, anglais, allemand).
//!
//! Seuls les libellés fixes de la mise en page sont traduits ici ; les
//! textes libres de l'attestation (méthode, réserves) sont rédigés par
//! l'appelant dans la langue voulue avant signature. Les gabarits utilisent
//! des marqueurs `{nom}` remplis par [`fill`].

/// Langue du certificat.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Lang {
    /// Français (langue historique des certificats).
    #[default]
    Fr,
    /// Anglais.
    En,
    /// Allemand.
    De,
}

impl Lang {
    /// Toutes les langues.
    pub const ALL: [Lang; 3] = [Lang::Fr, Lang::En, Lang::De];

    /// Libellés de cette langue.
    pub(crate) fn texts(self) -> &'static Texts {
        match self {
            Lang::Fr => &FR,
            Lang::En => &EN,
            Lang::De => &DE,
        }
    }
}

/// Remplace les marqueurs `{nom}` de `template`.
pub(crate) fn fill(template: &str, args: &[(&str, &str)]) -> String {
    let mut text = template.to_string();
    for (name, value) in args {
        text = text.replace(&format!("{{{name}}}"), value);
    }
    text
}

